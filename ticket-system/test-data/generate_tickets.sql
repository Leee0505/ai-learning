SELECT status, COUNT(*) AS cnt, ROUND(COUNT(*)/(SELECT COUNT(*) FROM ticket)*100, 1) AS pct
FROM ticket GROUP BY status ORDER BY FIELD(status, 'OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED');
